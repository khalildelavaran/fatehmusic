- دست چپ یا راست بیش از حد منقبض می‌شود
- نت‌ها از نظر ارتفاع مرتباً ناپایدار هستند
- ریتم در طول قطعه تغییر می‌کند
- تمرین زیاد است اما صدادهی و هماهنگی پیشرفت نمی‌کند

در چنین شرایطی، تمرین را ساده‌تر کنید، سرعت را پایین بیاورید و از مدرس بازخورد بگیرید.

