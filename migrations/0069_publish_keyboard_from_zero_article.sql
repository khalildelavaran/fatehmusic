1. بخش دست راست را جداگانه تمرین کنید.
2. بخش دست چپ را جداگانه تمرین کنید.
3. هر دو بخش را با سرعت پایین ترکیب کنید.
4. نقاط دشوار را جداگانه تکرار کنید.
5. بعد از تثبیت، سرعت را کمی افزایش دهید.

اگر از ابتدا با سرعت بالا تمرین کنید، احتمال خطا و توقف بیشتر می‌شود.

