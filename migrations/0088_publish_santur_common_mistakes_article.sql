**راهکار:** برنامه‌ای واقع‌بینانه تنظیم کنید و در طول هفته تمرین‌های منظم و متمرکز داشته باشید.

## اشتباه دوازدهم: تغییر مداوم روش و منبع آموزشی

استفاده هم‌زمان از چند روش آموزشی می‌تواند ترتیب مباحث و تمرین‌ها را نامنظم کند.

**راهکار:** یک مسیر آموزشی مشخص داشته باشید و منابع جانبی را با هدف مشخص و در زمان مناسب اضافه کنید.

## اشتباه سیزدهم: بی‌توجهی به شنیدن صدای ساز

گاهی هنرجو بیشتر به حرکت دست‌ها و نت‌ها توجه می‌کند و کمتر به صدایی که تولید می‌شود گوش می‌دهد.

**راهکار:** بخشی از تمرین را با تمرکز کامل روی کیفیت صدا انجام دهید و در صورت امکان اجرای خود را ضبط و بررسی کنید.

