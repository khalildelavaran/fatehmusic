یک مسیر مقدماتی مناسب بهتر است از شناخت ساز و وضعیت صحیح نشستن شروع شود و سپس به گرفتن مضراب، تولید صدای تمیز، شناخت نت‌ها، ریتم و اجرای الگوهای ساده برسد.

