## اشتباه اول: گرفتن نادرست مضراب

نحوه قرار گرفتن مضراب در دست، آزادی حرکت و کنترل ضربه را تحت تأثیر قرار می‌دهد. اگر مضراب بیش از حد سفت یا نامناسب گرفته شود، حرکت طبیعی دست دشوارتر می‌شود.

**راهکار:** از همان ابتدا روش صحیح گرفتن مضراب را زیر نظر مدرس یاد بگیرید و روی حرکت آزاد و کنترل‌شده دست تمرکز کنید.

## اشتباه دوم: ضربه زدن با فشار بیش از حد

بعضی هنرجویان برای تولید صدای واضح‌تر، ضربه را با نیروی زیاد وارد می‌کنند. این کار می‌تواند باعث خستگی و کاهش کنترل شود.

**راهکار:** هدف را تولید صدای تمیز و یکنواخت قرار دهید، نه صرفاً ضربه شدید. شدت مناسب را با کنترل حرکت پیدا کنید.

## اشتباه سوم: بی‌توجهی به کوک سنتور

کوک مناسب برای تمرین نت‌خوانی و تشخیص صدای درست اهمیت زیادی دارد. اگر ساز مرتباً از کوک خارج باشد، گوش هنرجو ممکن است مرجع صوتی مناسبی برای تمرین نداشته باشد.

**راهکار:** وضعیت کوک ساز را به‌صورت منظم بررسی کنید و در صورت نیاز از فرد باتجربه یا مدرس برای کوک کمک بگیرید.

## اشتباه چهارم: تمرین قطعه با ساز خارج از کوک

حتی اگر هنرجو نت‌ها را درست بزند، اجرای قطعه با ساز خارج از کوک می‌تواند تشخیص صدای صحیح را دشوار کند.

**راهکار:** پیش از تمرین قطعات، وضعیت کوک ساز را بررسی کنید و در صورت نیاز آن را تنظیم کنید.

## اشتباه پنجم: عجله برای اجرای سرعت بالا

در سنتور، افزایش سرعت بدون تثبیت حرکت مضراب‌ها و هماهنگی دو دست می‌تواند باعث بی‌دقتی و ایجاد ضربه‌های نامنظم شود.

**راهکار:** قطعه یا تمرین را ابتدا آهسته اجرا کنید و فقط پس از تثبیت دقت، سرعت را مرحله‌به‌مرحله افزایش دهید.

## اشتباه ششم: تمرین بدون شمارش و مترونوم

بعضی هنرجویان هنگام تمرین بیشتر روی محل نت‌ها تمرکز می‌کنند و ریتم را به احساس شخصی می‌سپارند.

**راهکار:** ضرب را بشمارید و در تمرین‌های مناسب از مترونوم استفاده کنید تا ثبات زمانی و کنترل سرعت بهتر شود.

## اشتباه هفتم: تمرکز بیش از حد روی یک دست

گاهی هنرجو در ابتدای مسیر یک دست را راحت‌تر می‌داند و بیشتر با همان تمرین می‌کند. این موضوع می‌تواند باعث شود هماهنگی دو دست دیرتر شکل بگیرد.

**راهکار:** تمرین‌های مستقل برای هر دست داشته باشید، اما ترکیب دو دست را نیز به‌صورت تدریجی وارد برنامه کنید.

## اشتباه هشتم: نادیده گرفتن نت‌خوانی

حفظ کردن محل نت‌ها روی ساز یا تقلید از مدرس می‌تواند در مراحل اولیه کمک‌کننده باشد، اما وابستگی کامل به حافظه یا تقلید، یادگیری قطعات جدید را محدود می‌کند.

**راهکار:** نت‌خوانی را از تمرین‌های ساده شروع کنید و آن را هم‌زمان با نوازندگی توسعه دهید.

## اشتباه نهم: توجه نکردن به کیفیت و یکنواختی صدا

در سنتور، فقط درست بودن نت کافی نیست. تفاوت شدت ضربه‌ها و کیفیت صدا نیز روی اجرای موسیقی اثر دارد.

**راهکار:** بعضی تمرین‌ها را با تمرکز کامل بر یکنواختی ضربه‌ها و کیفیت صدای هر دو دست انجام دهید.

