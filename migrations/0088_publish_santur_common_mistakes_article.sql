## یک برنامه تمرین ساده برای سنتور

برای جلوگیری از تمرین پراکنده می‌توان جلسه را به بخش‌های مشخص تقسیم کرد:

### ۱. آماده‌سازی

وضعیت نشستن و گرفتن مضراب را بررسی کنید و چند ضربه ساده و کنترل‌شده بزنید.

### ۲. تکنیک مضراب

یک تمرین مشخص برای کنترل ضربه‌های راست و چپ انجام دهید.

### ۳. نت‌خوانی

یک تمرین کوتاه را با تمرکز بر نت‌ها و ریتم اجرا کنید.

### ۴. هماهنگی دو دست

یک الگوی کوتاه را ابتدا آهسته و سپس با سرعت مناسب اجرا کنید.

### ۵. قطعه

بخش دشوار قطعه را جداگانه تمرین کنید و پس از تثبیت، آن را به بخش‌های دیگر متصل کنید.

### ۶. مرور

در پایان، اجرای کوتاهی از تمرین‌های تثبیت‌شده داشته باشید و نقاطی را که نیاز به اصلاح دارند یادداشت کنید.

## از کجا بفهمیم روش تمرین سنتور نیاز به اصلاح دارد؟

اگر یک مشکل مشخص با وجود تکرار زیاد همچنان باقی می‌ماند، احتمالاً فقط تعداد تکرارها کافی نیست و باید روش تمرین تغییر کند.

نشانه‌هایی مانند این موارد می‌توانند نیاز به اصلاح روش تمرین را نشان دهند:

- ضربه‌ها از نظر شدت و کیفیت بسیار متفاوت هستند
- هنگام افزایش سرعت، هماهنگی دو دست از بین می‌رود
- یک بخش مشخص قطعه همیشه دچار خطا می‌شود
- ساز مرتباً از کوک خارج می‌شود و تمرین بدون بررسی کوک ادامه پیدا می‌کند
- نت‌خوانی باعث توقف مداوم اجرای قطعه می‌شود
- تمرین زیاد است اما کیفیت و کنترل ضربه‌ها پیشرفت نمی‌کند

در چنین شرایطی، تمرین را ساده‌تر کنید، سرعت را کاهش دهید و از مدرس بازخورد بگیرید.

