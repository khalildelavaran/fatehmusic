هنگام انتخاب ساز، مواردی مانند تعداد کلاویه‌ها، اندازه و کیفیت کلاویه، حساسیت به شدت نوازندگی و شرایط فضای تمرین را در نظر بگیرید.

اگر در انتخاب ساز مطمئن نیستید، مشورت با مدرس یا فرد باتجربه می‌تواند از خرید نامتناسب جلوگیری کند.

