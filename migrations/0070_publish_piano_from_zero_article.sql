یادگیری **پیانو** می‌تواند از سطح کاملاً مقدماتی شروع شود. برای شروع لازم نیست نت‌خوانی حرفه‌ای بلد باشید یا قبلاً ساز دیگری نواخته باشید. مسیر آموزش را می‌توان از شناخت ساز و نت‌ها آغاز کرد و به‌تدریج به هماهنگی دو دست، آکورد، ریتم و اجرای قطعه رسید.

