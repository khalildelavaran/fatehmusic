## یک برنامه تمرین ساده برای ارگ و کیبورد

برای جلوگیری از تمرین پراکنده می‌توان جلسه را به چند بخش تقسیم کرد:

### ۱. آماده‌سازی

چند دقیقه وضعیت نشستن، دست‌ها و تمرین‌های ساده انگشتان را مرور کنید.

### ۲. تکنیک

یک تمرین مشخص برای دست راست یا چپ انجام دهید.

### ۳. آکورد و ریتم

آکوردهای پایه و تعویض آنها را با شمارش تمرین کنید.

### ۴. هماهنگی دو دست

یک الگوی کوتاه را ابتدا آهسته و سپس با سرعت مناسب اجرا کنید.

### ۵. قطعه

بخش کوتاهی از یک قطعه متناسب با سطح خود را تمرین کنید.

### ۶. مرور

در پایان، تمرین‌های قبلی را کوتاه مرور کنید و پیشرفت خود را بررسی کنید.

## از کجا بفهمیم روش تمرین ما اشتباه است؟

اگر با وجود تمرین مداوم، یک مشکل مشخص مرتب تکرار می‌شود، بهتر است روش تمرین را بررسی کنید.

نشانه‌هایی مانند این موارد می‌توانند نیاز به اصلاح روش تمرین را نشان دهند:

- یک بخش همیشه در یک نقطه خاص متوقف می‌شود
- هنگام افزایش سرعت خطاها ناگهان زیاد می‌شوند
- دست چپ یا راست به‌طور محسوسی عقب‌تر است
- ریتم در زمان اجرای قطعه ناپایدار می‌شود
- بدون نگاه کردن به دست‌ها اجرای قطعه دشوار است
- تمرین زیاد است اما مهارت‌های پایه رشد نمی‌کنند

در چنین شرایطی، بهتر است تمرین را به بخش‌های کوچک‌تر تقسیم کنید و از مدرس بازخورد بگیرید.

