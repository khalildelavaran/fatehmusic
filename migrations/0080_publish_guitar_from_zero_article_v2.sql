## اشتباهات رایج در آموزش گیتار

### عجله برای سرعت

سرعت زیاد قبل از تثبیت حرکت‌ها باعث افزایش خطا می‌شود.

**راهکار:** ابتدا دقت و کنترل را تثبیت کنید و سپس سرعت را افزایش دهید.

### فشار بیش از حد دست چپ

فشار زیاد انگشت‌ها روی سیم‌ها همیشه به صدای بهتر منجر نمی‌شود و می‌تواند دست را خسته کند.

**راهکار:** فشار لازم برای صدای واضح را پیدا کنید و حرکت انگشت‌ها را تا حد امکان اقتصادی نگه دارید.

### تمرین بدون کوک

تمرین مداوم با گیتار ناکوک می‌تواند تشخیص ارتفاع درست صدا را دشوار کند.

**راهکار:** قبل از تمرین کوک ساز را بررسی کنید.

### بی‌توجهی به ریتم

تمرکز فقط روی آکوردها بدون توجه به ضرب، اجرای موسیقی را ناپایدار می‌کند.

**راهکار:** از همان مراحل ابتدایی شمارش و مترونوم را وارد تمرین کنید.

### یادگیری تعداد زیادی آکورد بدون تمرین

حفظ کردن شکل آکوردها به‌تنهایی باعث روان شدن نوازندگی نمی‌شود.

**راهکار:** چند آکورد پایه را انتخاب کنید و تعویض آنها را به‌صورت منظم تمرین کنید.

### شروع هم‌زمان چند سبک

تلاش برای یادگیری هم‌زمان چند مسیر کاملاً متفاوت ممکن است تمرکز هنرجوی مبتدی را کاهش دهد.

**راهکار:** ابتدا یک مسیر مناسب هدف خود انتخاب کنید و بعد دامنه مهارت‌ها را گسترش دهید.

### تمرین نامنظم

تمرین‌های پراکنده روند تثبیت مهارت را کند می‌کنند.

**راهکار:** برنامه‌ای کوتاه، منظم و قابل اجرا داشته باشید.

