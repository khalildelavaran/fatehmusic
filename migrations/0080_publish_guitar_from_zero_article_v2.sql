انتخاب ساز مناسب، تجربه یادگیری را راحت‌تر می‌کند. در بازار انواع گیتار از جمله کلاسیک، فلامنکو، آکوستیک و الکتریک وجود دارد و هرکدام ویژگی‌های متفاوتی دارند.

برای هنرجوی مبتدی بهتر است ساز از نظر اندازه، سلامت، کوک‌پذیری و راحتی دست گرفتن مناسب باشد.

اگر هنوز سبک مورد علاقه خود را نمی‌شناسید، می‌توانید در جلسات ابتدایی با راهنمایی مدرس درباره انتخاب ساز تصمیم بگیرید.

## آشنایی با اجزای گیتار

پیش از تمرین جدی بهتر است هنرجو بخش‌های اصلی گیتار را بشناسد؛ از جمله:

- دسته
- فرت‌ها
- سیم‌ها
- خرک
- گوشی‌های کوک
- بدنه
- سوراخ صدا در گیتارهای آکوستیک و کلاسیک

شناخت این بخش‌ها باعث می‌شود توضیحات آموزشی و تمرین‌های بعدی راحت‌تر دنبال شوند.

## وضعیت صحیح نشستن و گرفتن گیتار

وضعیت بدن و دست‌ها از همان ابتدا اهمیت دارد. گیتار باید در موقعیتی قرار بگیرد که دست راست یا دست مضراب‌زن بتواند آزادانه حرکت کند و دست چپ نیز به فرت‌ها دسترسی مناسبی داشته باشد.

در شروع، بهتر است به جای سرعت، روی راحتی، تعادل ساز و حرکت طبیعی دست‌ها تمرکز کنید.

## کوک کردن گیتار

گیتار باید پیش از تمرین در کوک مناسب باشد. تمرین روی ساز ناکوک می‌تواند گوش هنرجو را نسبت به ارتفاع صحیح نت‌ها دچار مشکل کند.

هنرجوی مبتدی می‌تواند با کمک تیونر دیجیتال یا راهنمایی مدرس، کوک کردن را یاد بگیرد.

یادگیری کوک یکی از مهارت‌های کاربردی است که بهتر است از همان مراحل ابتدایی تمرین شود.

## مضراب و ضربه‌های پایه

یکی از نخستین مهارت‌ها، کنترل ضربه‌های دست راست است.

در آموزش مقدماتی ممکن است تمرین‌هایی مانند ضربه‌های رو به پایین و بالا، الگوهای ساده مضراب و حرکت منظم دست آموزش داده شود.

هدف اولیه، ایجاد حرکت کنترل‌شده و هماهنگ با ضرب است؛ نه اجرای سریع.

## آکوردهای پایه گیتار

آکوردها برای بسیاری از هنرجویانی که هدفشان همراهی با آواز یا اجرای آهنگ‌های ساده است، اهمیت زیادی دارند.

در سطح مقدماتی معمولاً چند آکورد ساده آموزش داده می‌شود و سپس هنرجو تمرین می‌کند بین آنها بدون توقف طولانی جابه‌جا شود.

تمرین تعویض آکورد باید ابتدا آهسته انجام شود. وقتی حرکت انگشت‌ها تثبیت شد، سرعت به‌تدریج افزایش پیدا می‌کند.

## ریتم و مترونوم

آکورد بدون ریتم منظم، اجرای موسیقی را ناقص می‌کند. بنابراین در کنار آکوردها باید ضرب و الگوهای ریتمیک نیز تمرین شوند.

مترونوم می‌تواند به هنرجو کمک کند ضرب ثابت را حفظ کند. بهتر است ابتدا با سرعتی تمرین کنید که همه حرکت‌ها دقیق باشند و سپس سرعت را مرحله‌به‌مرحله افزایش دهید.

## نت‌خوانی و تئوری موسیقی

برای یادگیری گیتار، آشنایی با نت‌ها و مفاهیم پایه موسیقی می‌تواند بسیار مفید باشد.

بسته به مسیر آموزشی، هنرجو ممکن است با موارد زیر آشنا شود:

