## چگونه آموزش تنبک را درست شروع کنیم؟

یک مسیر مقدماتی مناسب بهتر است از شناخت ساز و وضعیت صحیح نشستن شروع شود و سپس به صداهای پایه، ریتم، هماهنگی دست‌ها و اجرای الگوهای ساده برسد.

