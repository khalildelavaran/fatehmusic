پیش از شروع می‌توانید بازی‌های ساده‌ای انجام دهید؛ مثلاً از کودک بخواهید یک الگوی دست‌زدن را تقلید کند یا پس از شنیدن چند ضرب، همان الگو را تکرار کند. هدف سنجش یا نمره دادن نیست. این فعالیت فقط به شما نشان می‌دهد که کودک به تجربه‌های موسیقایی کوتاه چه واکنشی دارد.

## ۳. هماهنگی دست‌ها و راحتی با ساز

گیتار برای نواختن به هماهنگی میان دو دست نیاز دارد. یک دست نت یا آکورد را شکل می‌دهد و دست دیگر سیم‌ها را به صدا درمی‌آورد. در ابتدای مسیر، انجام هم‌زمان این حرکت‌ها ممکن است دشوار باشد؛ این موضوع برای مبتدی‌ها طبیعی است.

لازم نیست کودک پیش از شروع، هماهنگی پیشرفته‌ای داشته باشد. تمرین‌ها دقیقاً برای رشد تدریجی این توانایی طراحی می‌شوند. آنچه اهمیت دارد، راحتی نسبی هنگام نگه داشتن ساز، امکان قرار گرفتن آن در وضعیت مناسب و متناسب بودن اندازه ساز با بدن کودک است.

