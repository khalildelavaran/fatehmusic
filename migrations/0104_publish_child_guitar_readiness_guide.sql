اگر کودک خیلی زود خسته می‌شود، فوراً نتیجه نگیرید که برای همیشه آماده نیست. شاید فعالیت طولانی یا دشوار بوده، زمان مناسبی انتخاب نشده یا روش معرفی ساز برای او جذاب نبوده است. می‌توان مدتی با بازی‌های ریتمیک و آشنایی کوتاه شروع کرد و بعد دوباره شرایط را سنجید.

