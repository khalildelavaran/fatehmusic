خبر خوب این است که بیشتر مشکلات مبتدی‌ها را می‌توان با مشاهده دقیق، ساده کردن تمرین و دریافت بازخورد مناسب بررسی کرد. لازم نیست همه چیز را یک‌باره اصلاح کنید. ابتدا مشخص کنید مشکل دقیقاً کجاست، سپس روی یک عامل تمرکز کنید و بعد نتیجه را دوباره ارزیابی کنید.

