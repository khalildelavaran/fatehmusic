در مراحل اول، بهتر است روی مهارت‌های پایه تمرکز شود: تنفس، کنترل صدا، تشخیص ارتفاع نت، تکرار جمله‌های کوتاه و حفظ ریتم. پس از ایجاد این پایه، هنرجو می‌تواند قطعات ساده‌تر بختیاری را با راهنمایی مدرس تمرین کند.

انتخاب قطعه متناسب با سطح اهمیت زیادی دارد. شروع با قطعه‌ای که از نظر محدوده صوتی یا پیچیدگی اجرایی بسیار دشوار است، لزوماً روند یادگیری را سریع‌تر نمی‌کند.

