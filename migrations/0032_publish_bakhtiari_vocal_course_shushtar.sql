آواز محلی بختیاری بخشی از فرهنگ شفاهی و موسیقی بومی مردم بختیاری است و در شیوه اجرا، ملودی، بیان شعر و حال‌وهوای روایی خود ویژگی‌های مشخصی دارد. به همین دلیل، آموزش آن فقط به خواندن یک متن یا تقلید سطحی از یک اجرای ضبط‌شده محدود نمی‌شود.

