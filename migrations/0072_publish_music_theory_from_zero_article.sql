برای مثال، شناخت گام‌ها به درک ساختار ملودی کمک می‌کند و شناخت ریتم باعث می‌شود الگوهای زمانی دقیق‌تر خوانده و اجرا شوند.

## نت‌خوانی و خطوط حامل

