شناخت ارزش زمانی نت‌ها و سکوت‌ها پایه‌ای برای درک ریتم است. هنرجو باید بتواند الگوهای ساده را بخواند، بشمارد و اجرا کند.

تمرین با دست زدن، شمارش یا مترونوم می‌تواند در این مرحله مفید باشد.

## ریتم و میزان

