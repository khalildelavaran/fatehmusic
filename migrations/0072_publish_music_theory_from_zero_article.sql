هنرجو باید بتواند جای نت را روی حامل تشخیص دهد و آن را به صدای واقعی یا جای آن روی ساز ارتباط دهد.

بهتر است نت‌خوانی صرفاً به حفظ کردن نام نت‌ها محدود نشود؛ تمرین عملی باعث می‌شود این مهارت کاربردی‌تر شود.

## ارزش زمانی نت‌ها و سکوت‌ها

