فشار زیاد می‌تواند باعث خستگی و کاهش آزادی حرکت انگشت‌ها شود.

**راهکار:** جای مناسب انگشت روی فرت را پیدا کنید و فقط به اندازه لازم فشار وارد کنید.

## اشتباه چهارم: وضعیت نادرست دست راست

