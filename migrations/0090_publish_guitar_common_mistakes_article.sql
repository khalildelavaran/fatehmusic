## یک برنامه تمرین ساده برای گیتار

برای جلوگیری از تمرین پراکنده می‌توان جلسه را به بخش‌های مشخص تقسیم کرد:

### ۱. آماده‌سازی

کوک ساز، وضعیت نشستن و حالت دست‌ها را بررسی کنید.

### ۲. تکنیک

یک تمرین مشخص برای انگشت‌گذاری، تعویض آکورد یا حرکت دست راست انجام دهید.

### ۳. ریتم

یک الگوی ریتمیک کوتاه را با شمارش و در صورت نیاز مترونوم تمرین کنید.

### ۴. آکورد

دو یا چند آکورد را با تعویض آرام و دقیق تمرین کنید.

### ۵. قطعه

بخش دشوار قطعه را جداگانه تمرین کنید و سپس آن را به بخش‌های دیگر متصل کنید.

### ۶. مرور

در پایان، قطعه یا تمرین‌های تثبیت‌شده را یک بار با سرعت مناسب اجرا کنید.

## از کجا بفهمیم روش تمرین گیتار نیاز به اصلاح دارد؟

اگر یک مشکل مشخص با وجود تکرار زیاد همچنان باقی می‌ماند، احتمالاً فقط تعداد تکرارها کافی نیست و باید روش تمرین تغییر کند.

نشانه‌هایی مانند این موارد می‌توانند نیاز به اصلاح روش تمرین را نشان دهند:

- آکوردها هنگام تعویض صدای واضحی ندارند
- ریتم هنگام افزایش سرعت ناپایدار می‌شود
- دست چپ یا راست بیش از حد خسته می‌شود
- یک بخش مشخص قطعه همیشه دچار خطا می‌شود
- گیتار مرتباً از کوک خارج می‌شود و تمرین بدون بررسی ادامه پیدا می‌کند
- تمرین زیاد است اما تعویض آکورد و هماهنگی دو دست پیشرفت نمی‌کند

در چنین شرایطی، تمرین را ساده‌تر کنید، سرعت را پایین بیاورید و از مدرس بازخورد بگیرید.

