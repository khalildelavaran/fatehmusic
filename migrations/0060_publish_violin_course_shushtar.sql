## ویولن چیست و یادگیری آن شامل چه مهارت‌هایی است؟

ویولن سازی زهی و آرشه‌ای است که صدای آن با حرکت آرشه روی سیم‌ها تولید می‌شود. از آنجا که روی دسته ساز فرت مشخصی وجود ندارد، پیدا کردن دقیق جای نت‌ها تا حد زیادی به هماهنگی دست و گوش نوازنده وابسته است.

