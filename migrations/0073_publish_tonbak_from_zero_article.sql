در مسیر آموزشی، هنرجو به‌تدریج تفاوت میان صداهای پایه و محل‌های مختلف ضربه را می‌آموزد. هدف این نیست که فقط ضربه‌ها را سریع اجرا کند؛ کیفیت و یکنواختی صدا نیز اهمیت دارد.

