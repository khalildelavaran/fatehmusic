## نحوه صحیح نشستن و گرفتن تنبک

پیش از یادگیری ریتم‌های پیچیده، وضعیت بدن و ساز باید تا حد امکان راحت و کنترل‌شده باشد.

هنرجو باید بتواند بدون فشار غیرضروری روی دست‌ها و شانه‌ها ساز را در موقعیت مناسب نگه دارد. وضعیت نامناسب بدن می‌تواند در تمرین‌های طولانی باعث خستگی شود و کنترل حرکات را دشوار کند.

به همین دلیل، اصلاح حالت نشستن و دست‌ها بهتر است از همان جلسات ابتدایی انجام شود.

## شناخت صداهای پایه

