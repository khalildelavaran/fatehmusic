**راهکار:** بخشی از تمرین را با مترونوم و بخشی را بدون آن انجام دهید؛ سپس اجرای خود را با ضرب مرجع مقایسه کنید.

## اشتباه چهارم: بی‌توجهی به سکوت‌ها

