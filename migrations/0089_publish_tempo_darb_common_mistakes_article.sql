## یک برنامه تمرین ساده برای ضرب تمپو

برای جلوگیری از تمرین پراکنده می‌توان جلسه را به بخش‌های مشخص تقسیم کرد:

### ۱. آماده‌سازی

چند دقیقه ضرب را با شمارش آرام و منظم دنبال کنید.

### ۲. الگوی پایه

یک الگوی کوتاه را با سرعت پایین اجرا کنید و روی ثبات ضرب تمرکز داشته باشید.

### ۳. مترونوم

همان الگو را با مترونوم تمرین کنید و سرعت را ثابت نگه دارید.

### ۴. بدون مترونوم

برای بخشی از تمرین مترونوم را کنار بگذارید و تلاش کنید ضرب را در ذهن حفظ کنید.

### ۵. الگوی جدید

یک تغییر کوچک به الگو اضافه کنید و دوباره آن را آهسته تمرین کنید.

### ۶. مرور

در پایان، الگوهای قبلی را با سرعت مناسب اجرا کنید و نقاط ضعف را یادداشت کنید.

## از کجا بفهمیم روش تمرین ضرب تمپو نیاز به اصلاح دارد؟

اگر یک مشکل مشخص با وجود تکرار زیاد همچنان باقی می‌ماند، احتمالاً فقط تعداد تکرارها کافی نیست و باید روش تمرین تغییر کند.

نشانه‌هایی مانند این موارد می‌توانند نیاز به اصلاح روش تمرین را نشان دهند:

- سرعت در طول اجرا تغییر می‌کند
- ضرب‌ها در بعضی بخش‌ها جلو یا عقب می‌افتند
- با حذف مترونوم ثبات ریتم از بین می‌رود
- سکوت‌ها درست زمان‌بندی نمی‌شوند
- هنگام افزایش سرعت، هماهنگی کاهش پیدا می‌کند
- تمرین زیاد است اما حس زمان و دقت ریتم پیشرفت نمی‌کند

در چنین شرایطی، سرعت را پایین بیاورید، الگو را ساده‌تر کنید و از مدرس بازخورد بگیرید.

