2. چند دقیقه تمرین تکنیک یا تمرین مشخص‌شده در کلاس.
3. چند دقیقه مرور آکورد، نت یا الگوی ریتمی.
4. چند دقیقه کار روی بخشی از قطعه‌ای که در حال یادگیری آن هستید.
5. یادداشت کردن یک نکته که در جلسه بعد باید دوباره بررسی شود.

