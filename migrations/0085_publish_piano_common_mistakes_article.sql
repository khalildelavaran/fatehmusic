## یک برنامه تمرین ساده برای پیانو

برای جلوگیری از تمرین پراکنده می‌توان یک جلسه را به بخش‌های مشخص تقسیم کرد:

### ۱. آماده‌سازی

چند دقیقه وضعیت نشستن، دست‌ها و تمرین‌های ساده انگشتان را مرور کنید.

### ۲. نت‌خوانی

یک تمرین کوتاه را با تمرکز بر خواندن و ریتم اجرا کنید.

### ۳. تکنیک

یک تمرین مشخص برای استقلال انگشت‌ها یا هماهنگی دست‌ها انجام دهید.

### ۴. قطعه

بخش دشوار قطعه را به قسمت‌های کوچک تقسیم کنید و با سرعت پایین تمرین کنید.

### ۵. ریتم و مترونوم

بخش موردنظر را با سرعت ثابت اجرا کنید و در صورت نیاز از مترونوم کمک بگیرید.

### ۶. مرور

در پایان، یک اجرای کوتاه از بخش‌های تثبیت‌شده داشته باشید.

## از کجا بفهمیم روش تمرین پیانو نیاز به اصلاح دارد؟

اگر یک مشکل مشخص با وجود تکرار زیاد همچنان باقی می‌ماند، احتمالاً فقط تعداد تکرارها کافی نیست و باید روش تمرین تغییر کند.

نشانه‌هایی مانند موارد زیر می‌توانند نیاز به اصلاح تمرین را نشان دهند:

- خطا همیشه در یک بخش مشخص تکرار می‌شود
- با افزایش سرعت، اجرای قطعه به‌سرعت از کنترل خارج می‌شود
- یک دست به‌طور محسوسی از دست دیگر عقب‌تر است
- ریتم در طول قطعه تغییر می‌کند
- بدون نگاه کردن به نت‌ها یا دست‌ها اجرای قطعه دشوار است
- تمرین زیاد است اما مهارت‌های پایه پیشرفت نمی‌کنند

در چنین شرایطی، قطعه را کوچک‌تر کنید، سرعت را پایین بیاورید و از مدرس بازخورد بگیرید.

