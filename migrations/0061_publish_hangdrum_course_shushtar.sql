### آشنایی با ساز و ساختار نت‌ها

هنرجو با بخش‌های مختلف ساز، نت‌ها و نحوه چیدمان آنها آشنا می‌شود. شناخت محل نت‌ها باعث می‌شود در ادامه بتواند بدون نگاه مداوم به ساز، مسیرهای ملودیک ساده را بهتر پیدا کند.

### وضعیت صحیح نوازندگی

