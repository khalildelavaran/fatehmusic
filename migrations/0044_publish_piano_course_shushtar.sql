در یک مسیر آموزشی مناسب، مفاهیم از پایه معرفی می‌شوند و هم‌زمان با اجرای ساز پیش می‌روند. این نکته مهم است که آموزش تئوری از نوازندگی جدا نشود؛ هنرجو باید بتواند مفهومی را که یاد می‌گیرد روی کلاویه‌ها ببیند و صدای آن را بشنود.

