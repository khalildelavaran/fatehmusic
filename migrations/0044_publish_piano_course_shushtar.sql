اگر در شوشتر زندگی می‌کنید و قصد شروع پیانو دارید، بهتر است قبل از ثبت‌نام درباره سطح دوره، شیوه آموزش، سرفصل‌ها و هدف کلاس اطلاعات کافی داشته باشید. برای هنرجوی مبتدی، مهم است که آموزش از پایه و با سرعت قابل فهم پیش برود.

همچنین بهتر است مسیر آموزش فقط به حفظ قطعه محدود نشود. ترکیب نت‌خوانی، ریتم، تکنیک، تئوری موسیقی و اجرای قطعات می‌تواند پایه محکم‌تری برای ادامه مسیر ایجاد کند.

