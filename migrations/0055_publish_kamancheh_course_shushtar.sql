## کمانچه چیست و یادگیری آن شامل چه مهارت‌هایی است؟

کمانچه سازی زهی و آرشه‌ای است. صدای ساز با حرکت آرشه روی سیم‌ها ایجاد می‌شود و دست دیگر نوازنده وظیفه کنترل جایگاه نت‌ها روی دسته ساز را بر عهده دارد.

