قرار نیست هنرجو همه انواع گام و آکورد را یک‌باره حفظ کند. مهم‌تر از حفظ فهرست‌ها، درک منطق ساخت آن‌ها و توانایی استفاده از مفاهیم در مثال‌های واقعی است.

