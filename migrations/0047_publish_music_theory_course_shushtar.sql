برای مثال، دانستن تعریف یک گام زمانی کاربردی‌تر می‌شود که هنرجو بتواند آن را تشخیص دهد، روی ساز اجرا کند یا ارتباط آن را با یک قطعه ببیند. همین موضوع درباره ریتم، فواصل و آکوردها نیز صدق می‌کند.

